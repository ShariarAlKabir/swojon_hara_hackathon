CREATE TABLE users (
    id SERIAL PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(120) UNIQUE NOT NULL,
    phone VARCHAR(20) UNIQUE NOT NULL,
    nid VARCHAR(30) UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,

    profile_picture TEXT,

    ward VARCHAR(50),
    area VARCHAR(100),

    latitude DECIMAL(10,7),
    longitude DECIMAL(10,7),

    is_verified BOOLEAN DEFAULT FALSE,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TYPE report_status AS ENUM (
    'REPORTED',
    'IN_PROGRESS',
    'FIXED'
);

CREATE TYPE report_category AS ENUM (
    'STREETLIGHT',
    'GARBAGE',
    'POTHOLE',
    'OPEN_MANHOLE',
    'FLOODING',
    'OTHER'
);

CREATE TABLE reports (
    id SERIAL PRIMARY KEY,

    user_id INT REFERENCES users(id) ON DELETE CASCADE,

    title VARCHAR(150),

    description TEXT NOT NULL,

    category report_category NOT NULL,

    status report_status DEFAULT 'REPORTED',

    ward VARCHAR(50),

    area VARCHAR(100),

    latitude DECIMAL(10,7) NOT NULL,

    longitude DECIMAL(10,7) NOT NULL,

    supporter_count INT DEFAULT 0,

    is_trending BOOLEAN DEFAULT FALSE,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE report_images (

    id SERIAL PRIMARY KEY,

    report_id INT REFERENCES reports(id) ON DELETE CASCADE,

    image_url TEXT NOT NULL,

    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE report_updates (

    id SERIAL PRIMARY KEY,

    report_id INT REFERENCES reports(id) ON DELETE CASCADE,

    user_id INT REFERENCES users(id),

    note TEXT,

    image_url TEXT,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);


CREATE TYPE verification_type AS ENUM(
    'STILL_THERE',
    'MARK_FIXED'
);

CREATE TABLE report_verifications (

    id SERIAL PRIMARY KEY,

    report_id INT REFERENCES reports(id) ON DELETE CASCADE,

    user_id INT REFERENCES users(id),

    verification verification_type,

    image_url TEXT,

    latitude DECIMAL(10,7),

    longitude DECIMAL(10,7),

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE report_supports (

    id SERIAL PRIMARY KEY,

    report_id INT REFERENCES reports(id) ON DELETE CASCADE,

    user_id INT REFERENCES users(id),

    note TEXT,

    latitude DECIMAL(10,7),

    longitude DECIMAL(10,7),

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    UNIQUE(report_id,user_id)
);

CREATE TABLE cleanup_events (

    id SERIAL PRIMARY KEY,

    report_id INT REFERENCES reports(id) ON DELETE CASCADE,

    organizer_id INT REFERENCES users(id),

    event_date DATE,

    event_time TIME,

    description TEXT,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cleanup_participants (

    id SERIAL PRIMARY KEY,

    event_id INT REFERENCES cleanup_events(id) ON DELETE CASCADE,

    user_id INT REFERENCES users(id),

    joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    UNIQUE(event_id,user_id)
);

CREATE TABLE familiar_locations (

    id SERIAL PRIMARY KEY,

    user_id INT REFERENCES users(id),

    latitude DECIMAL(10,7),

    longitude DECIMAL(10,7),

    action_date DATE,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

